export type Dictionary = (typeof dictionary)['en']

/** Severity is a fixed enum, so its label is UI chrome rather than backend text. */
export function severityLabel(t: Dictionary, severity: Severity): string {
  const labels: Record<Severity, string> = {
    ok: t.severityOk,
    info: t.severityInfo,
    warn: t.severityWarn,
    critical: t.severityCritical,
  }
  return labels[severity]
}

/** Same for the monitor/alert badge the catalogue assigns each element. */
export function kindLabel(t: Dictionary, kind: ElementKind): string {
  return kind === 'alert' ? t.kindAlert : t.kindMonitor
}
